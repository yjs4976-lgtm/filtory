create table if not exists public.member_billing_profiles (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.members(id) on delete cascade,
  provider varchar(30) not null check (provider in ('TOSS', 'GOOGLE_PLAY', 'MOCK')),
  customer_key varchar(255) not null,
  encrypted_billing_key text,
  encryption_key_version varchar(30),
  status varchar(30) not null default 'pending' check (status in ('pending', 'active', 'revoked', 'verification_required')),
  card_company varchar(100),
