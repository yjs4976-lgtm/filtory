  provider varchar(30) not null check (provider in ('TOSS', 'GOOGLE_PLAY', 'MOCK')),
  provider_product_id varchar(255) not null,
  amount int not null check (amount >= 0),
  currency varchar(3) not null default 'KRW' check (currency = 'KRW'),
  billing_interval varchar(20) not null default 'month' check (billing_interval = 'month'),
  active boolean not null default true,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  unique(provider, provider_product_id)
