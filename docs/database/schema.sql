-- =========================================
-- 10. 새 회원 가입 시 free 플랜 자동 부여 함수
-- =========================================
create or replace function public.create_default_free_subscription()
returns trigger as $$
declare
  free_plan_id bigint;
begin
  select id
  into free_plan_id
  from public.subscription_plans
  where plan_code = 'free'
  limit 1;

  if free_plan_id is not null then
    insert into public.member_subscriptions (
      member_id,
      plan_id,
      status,
      started_at,
      current_period_start,
      current_period_end
    )
    values (
      new.id,
      free_plan_id,
      'active',
      now(),
      date_trunc('month', now()),
      date_trunc('month', now()) + interval '1 month'
    );
  end if;

  return new;
end;
$$ language plpgsql;


drop trigger if exists trg_members_create_default_subscription
on public.members;

create trigger trg_members_create_default_subscription
after insert on public.members
for each row
execute function public.create_default_free_subscription();


