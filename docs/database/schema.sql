-- 6. AI 분석 결과 테이블
-- =========================================
create table if not exists public.analysis_results (
  id bigint generated by default as identity primary key,

  member_id bigint references public.members(id) on delete set null,
  hospital_id bigint not null references public.hospitals(id) on delete cascade,
  review_id bigint not null references public.reviews(id) on delete cascade,

  total_score int,
  trust_score int,
  ad_score int,
  place_score int,
  foreigner_score int,

  trust_level varchar(30),
  ad_suspicion varchar(30),
  repetition_suspicion varchar(30),

  summary_ko text,
  summary_en text,

  evidence_json jsonb,
  ai_model varchar(100),

  created_at timestamp with time zone not null default now(),

  constraint analysis_total_score_check
    check (total_score is null or (total_score >= 0 and total_score <= 100)),

  constraint analysis_trust_score_check
    check (trust_score is null or (trust_score >= 0 and trust_score <= 100)),

  constraint analysis_ad_score_check
    check (ad_score is null or (ad_score >= 0 and ad_score <= 100)),

  constraint analysis_place_score_check
    check (place_score is null or (place_score >= 0 and place_score <= 100)),

  constraint analysis_foreigner_score_check
    check (foreigner_score is null or (foreigner_score >= 0 and foreigner_score <= 100))
);



