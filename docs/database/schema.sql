create table if not exists public.member_terms_agreements (
  id bigint generated by default as identity primary key,

  member_id bigint not null references public.members(id) on delete cascade,

  agreement_type varchar(30) not null,
  version varchar(50) not null default 'v1',

  agreed boolean not null default true,
  agreed_at timestamp with time zone not null default now(),

  revoked_at timestamp with time zone,

  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),

  constraint member_terms_agreements_type_check
    check (agreement_type in ('terms', 'privacy', 'marketing')),

  constraint member_terms_agreements_member_type_version_unique
    unique (member_id, agreement_type, version)
);

drop trigger if exists trg_member_terms_agreements_updated_at
on public.member_terms_agreements;

create trigger trg_member_terms_agreements_updated_at
before update on public.member_terms_agreements
for each row
execute function public.set_updated_at();

create index if not exists idx_member_terms_agreements_member_id
on public.member_terms_agreements(member_id);

create index if not exists idx_member_terms_agreements_type
on public.member_terms_agreements(agreement_type);

commit;
