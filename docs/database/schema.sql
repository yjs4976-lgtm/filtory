create table if not exists public.payment_transactions (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.members(id) on delete cascade,
  subscription_id bigint references public.member_subscriptions(id) on delete set null,
  billing_product_id bigint not null references public.billing_products(id),
  billing_profile_id bigint references public.member_billing_profiles(id) on delete set null,
  provider varchar(30) not null check (provider in ('TOSS', 'GOOGLE_PLAY', 'MOCK')),
  transaction_type varchar(30) not null check (transaction_type in ('INITIAL', 'RENEWAL', 'CANCEL', 'REFUND')),
  order_id varchar(255) not null,
  payment_key varchar(255),
  idempotency_key uuid not null unique,
  amount int not null check (amount >= 0),
  currency varchar(3) not null default 'KRW',
  status varchar(30) not null default 'READY' check (status in ('READY', 'IN_PROGRESS', 'DONE', 'FAILED', 'CANCELED', 'PARTIAL_CANCELED', 'ABORTED', 'EXPIRED')),
  requested_at timestamp with time zone not null default now(), approved_at timestamp with time zone,
  canceled_at timestamp with time zone, failure_code varchar(100), failure_message text,
  raw_response_json jsonb, created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  unique(provider, order_id), unique(provider, payment_key)
);

create table if not exists public.payment_webhook_events (
  id bigint generated by default as identity primary key,
  provider varchar(30) not null check (provider in ('TOSS', 'GOOGLE_PLAY', 'MOCK')),
  event_type varchar(100) not null, deduplication_key varchar(255) not null,
  payment_key varchar(255), processing_status varchar(30) not null default 'RECEIVED'
    check (processing_status in ('RECEIVED', 'PROCESSED', 'IGNORED', 'FAILED')),
  payload_json jsonb not null default '{}'::jsonb,
  received_at timestamp with time zone not null default now(), processed_at timestamp with time zone,
  error_message text, unique(provider, deduplication_key)
);

